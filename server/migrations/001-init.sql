CREATE TABLE IF NOT EXISTS settings(key TEXT PRIMARY KEY,value TEXT NOT NULL);
 CREATE TABLE IF NOT EXISTS projects(id TEXT PRIMARY KEY,revision INTEGER NOT NULL,json TEXT NOT NULL);
 CREATE TABLE IF NOT EXISTS revisions(project_id TEXT NOT NULL,revision INTEGER NOT NULL,json TEXT NOT NULL,PRIMARY KEY(project_id,revision));
 CREATE TABLE IF NOT EXISTS reviews(project_id TEXT NOT NULL,target_id TEXT NOT NULL,target_hash TEXT NOT NULL,json TEXT NOT NULL,PRIMARY KEY(project_id,target_id,target_hash));
 CREATE TABLE IF NOT EXISTS files(id TEXT PRIMARY KEY,project_id TEXT NOT NULL,json TEXT NOT NULL);
 CREATE TABLE IF NOT EXISTS jobs(id TEXT PRIMARY KEY,project_id TEXT NOT NULL,state TEXT NOT NULL,json TEXT NOT NULL);
 CREATE TABLE IF NOT EXISTS actions(project_id TEXT NOT NULL,key TEXT NOT NULL,input_hash TEXT NOT NULL,result TEXT NOT NULL,PRIMARY KEY(project_id,key));
 CREATE TABLE IF NOT EXISTS artifacts(id TEXT PRIMARY KEY,project_id TEXT NOT NULL,json TEXT NOT NULL);
 CREATE TABLE IF NOT EXISTS selections(project_id TEXT NOT NULL,shot_id TEXT NOT NULL,json TEXT NOT NULL,PRIMARY KEY(project_id,shot_id));
 CREATE TABLE IF NOT EXISTS sessions(token_hash TEXT PRIMARY KEY,expires INTEGER NOT NULL);
 CREATE INDEX IF NOT EXISTS jobs_state ON jobs(state);
